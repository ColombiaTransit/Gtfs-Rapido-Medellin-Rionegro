#!/usr/bin/env python3
"""Generate the GTFS feed for Rápido Medellín Rionegro.

Times and frequencies follow the operator's own route page:
https://www.rapidomedellin.com/rutas/intermunicipales/21

Where the operator gives a range ("every 6-15 minutes, depending on demand"),
the lower value is used in the weekday peaks and the upper value otherwise.
Colombian public holidays (python `holidays` package) run the weekend pattern.

Usage:
    python build_gtfs.py [--stops PATH] [--start YYYYMMDD] [--end YYYYMMDD] [--zip]

--stops is data/stops.csv from github.com/mvanlaar/colombia-stops
(default: ../colombia-stops/data/stops.csv).

shapes.txt is generated separately by build_shapes.py (GraphHopper).
"""

import argparse
import csv
import datetime as dt
import zipfile
from pathlib import Path

import holidays

ROOT = Path(__file__).resolve().parent

# Weekday peak periods (no official definition in Colombia; typical commuter peaks).
PEAKS = [("05:00:00", "08:30:00"), ("16:30:00", "19:30:00")]

AGENCY = {
    "agency_id": "RMR",
    "agency_name": "Rápido Medellín Rionegro",
    "agency_url": "https://www.rapidomedellin.com/",
    "agency_timezone": "America/Bogota",
    "agency_lang": "es",
    "agency_phone": "+57 604 480 1640",
}

# Stops come from the central stop registry (github.com/mvanlaar/colombia-stops).
# The registry stop_id is used as GTFS stop_id; name and coordinates are read from it.
RIONEGRO = "CO001362"     # Terminal de Rionegro (Rápido office, Cra 50 # 45-48)
AEROPUERTO = "CO002641"   # Aeropuerto Internacional José María Córdova
NORTE = "CO001433"        # Terminal del Norte, Medellín
SUR = "CO001432"          # Terminal del Sur, Medellín
STOP_IDS = [RIONEGRO, AEROPUERTO, NORTE, SUR]

# Fare networks (GTFS Fares v2): vans (aerovan) cost more than buses and
# microbuses on the same road, so they are a separate route in their own network.
NET_BUS = "bus"
NET_AEROVAN = "aerovan"
NETWORKS = [(NET_BUS, "Bus y microbús"), (NET_AEROVAN, "Aerovan")]

ROUTES = [
    # route_id, long name, desc, network
    ("RMR-RioNegro-TdT-Medellin-Norte", "Rionegro - Terminal del Norte", "Vía autopista Medellín - Bogotá. Bus y microbús", NET_BUS),
    ("RMR-RioNegro-TdT-Medellin-Norte-Van", "Rionegro - Terminal del Norte (aerovan)", "Vía autopista Medellín - Bogotá. Van", NET_AEROVAN),
    ("RMR-RioNegro-TdT-Medellin-Sur", "Rionegro - Terminal del Sur", "Vía Santa Elena - glorieta aeropuerto JMC", NET_BUS),
    ("RMR-RioNegro-TdT-Medellin-Norte-Llanogrande", "Rionegro - Terminal del Norte por Llanogrande",
     "Vía Llanogrande - aeropuerto JMC - autopista", NET_BUS),
]

# Fares 2026 (COP), in force since 2026-01-09, as published by the operator via
# DiariOriente: https://diarioriente.com/altiplano/sube-el-precio.html
# Fare areas are the stops; a leg is priced on its first and last stop.
FARE_AREAS = [("rionegro", "Rionegro", RIONEGRO), ("aeropuerto", "Aeropuerto JMC", AEROPUERTO),
              ("norte", "Terminal del Norte", NORTE), ("sur", "Terminal del Sur", SUR)]
FARE_PRODUCTS = [
    # fare_product_id, name, amount
    ("bus-13000", "Pasaje bus / microbús", 13000),
    ("bus-9500", "Pasaje Terminal del Norte - Aeropuerto", 9500),
    ("aerovan-15000", "Pasaje aerovan", 15000),
]
FARE_LEGS = [
    # network, area, area, product (rules are written for both directions)
    (NET_BUS, "rionegro", "norte", "bus-13000"),
    (NET_BUS, "rionegro", "sur", "bus-13000"),
    (NET_BUS, "aeropuerto", "norte", "bus-9500"),
    (NET_BUS, "aeropuerto", "sur", "bus-13000"),
    (NET_AEROVAN, "rionegro", "norte", "aerovan-15000"),
]

# Patterns: list of (stop_id, minutes after departure).
NORTE_OUT = [(RIONEGRO, 0), (NORTE, 60)]
NORTE_IN = [(NORTE, 0), (RIONEGRO, 60)]
SUR_OUT = [(RIONEGRO, 0), (AEROPUERTO, 30), (SUR, 90)]
SUR_IN = [(SUR, 0), (AEROPUERTO, 60), (RIONEGRO, 90)]
LLANO_OUT = [(RIONEGRO, 0), (AEROPUERTO, 30), (NORTE, 90)]

# Shapes are generated by build_shapes.py (GraphHopper).
SHAPE_NORTE_OUT = "norte-out"
SHAPE_NORTE_IN = "norte-in"
SHAPE_SUR_OUT = "sur-out"
SHAPE_SUR_IN = "sur-in"
SHAPE_LLANO_OUT = "llanogrande-out"

# Services operated, per the operator's page.
# vehicle, route_id, direction, headsign, pattern, shape, first, last, peak headway (min), base headway (min)
SERVICES = [
    ("Van", "RMR-RioNegro-TdT-Medellin-Norte-Van", 0, "Medellín - Terminal del Norte", NORTE_OUT, SHAPE_NORTE_OUT, "04:30:00", "22:00:00", 6, 15),
    ("Van", "RMR-RioNegro-TdT-Medellin-Norte-Van", 1, "Rionegro", NORTE_IN, SHAPE_NORTE_IN, "04:30:00", "22:00:00", 6, 15),
    ("Microbus", "RMR-RioNegro-TdT-Medellin-Norte", 0, "Medellín - Terminal del Norte", NORTE_OUT, SHAPE_NORTE_OUT, "04:30:00", "22:00:00", 7, 15),
    ("Microbus", "RMR-RioNegro-TdT-Medellin-Norte", 1, "Rionegro", NORTE_IN, SHAPE_NORTE_IN, "04:30:00", "22:00:00", 7, 15),
    ("Bus", "RMR-RioNegro-TdT-Medellin-Norte", 0, "Medellín - Terminal del Norte", NORTE_OUT, SHAPE_NORTE_OUT, "05:00:00", "20:00:00", 15, 15),
    ("Bus", "RMR-RioNegro-TdT-Medellin-Norte", 1, "Rionegro", NORTE_IN, SHAPE_NORTE_IN, "05:00:00", "20:00:00", 15, 15),
    ("Bus", "RMR-RioNegro-TdT-Medellin-Sur", 0, "Medellín - Terminal del Sur", SUR_OUT, SHAPE_SUR_OUT, "05:00:00", "20:00:00", 30, 30),
    ("Bus", "RMR-RioNegro-TdT-Medellin-Sur", 1, "Rionegro", SUR_IN, SHAPE_SUR_IN, "05:00:00", "20:00:00", 30, 30),
    ("Bus", "RMR-RioNegro-TdT-Medellin-Norte-Llanogrande", 0, "Medellín - Terminal del Norte", LLANO_OUT, SHAPE_LLANO_OUT, "06:00:00", "18:00:00", 60, 60),
]


def secs(t):
    h, m, s = map(int, t.split(":"))
    return h * 3600 + m * 60 + s


def hms(n):
    return f"{n // 3600:02d}:{n % 3600 // 60:02d}:{n % 60:02d}"


def frequency_blocks(first, last, peak_min, base_min, with_peaks):
    """Split [first, last] into periods with peak or base headways.

    end_time is set one second after the last departure so that the last
    departure listed by the operator is included.
    """
    start, end = secs(first), secs(last) + 1
    cuts = []
    if with_peaks and peak_min != base_min:
        for p0, p1 in PEAKS:
            a, b = max(secs(p0), start), min(secs(p1), end)
            if a < b:
                cuts.append((a, b))
    blocks, cur = [], start
    for a, b in cuts:
        if cur < a:
            blocks.append((cur, a, base_min))
        blocks.append((a, b, peak_min))
        cur = b
    if cur < end:
        blocks.append((cur, end, base_min))
    return [(hms(a), hms(b), m * 60) for a, b, m in blocks]


def write(name, header, rows):
    with open(ROOT / name, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


def load_stops(stops_csv):
    """Read the stops used by this feed from the colombia-stops registry."""
    with open(stops_csv, newline="", encoding="utf-8") as f:
        registry = {r["stop_id"]: r for r in csv.DictReader(f)}
    rows = []
    for sid in STOP_IDS:
        r = registry.get(sid)
        if r is None:
            raise SystemExit(f"{sid} not found in {stops_csv}")
        if not r["lat"] or not r["lon"] or r["notes"].startswith("NIET EXPORTEREN"):
            raise SystemExit(f"{sid} ({r['name']}) has no exportable coordinate in the registry")
        rows.append([sid, r["name"], r["lat"], r["lon"], r["url"]])
    return rows


def write_fares():
    """GTFS Fares v2: networks, areas, a cash fare medium, products and leg rules."""
    write("networks.txt", ["network_id", "network_name"], [list(n) for n in NETWORKS])
    write("areas.txt", ["area_id", "area_name"], [[a, name] for a, name, _ in FARE_AREAS])
    write("stop_areas.txt", ["area_id", "stop_id"], [[a, stop] for a, _, stop in FARE_AREAS])
    write("fare_media.txt", ["fare_media_id", "fare_media_name", "fare_media_type"], [["efectivo", "Efectivo", 0]])
    write("fare_products.txt", ["fare_product_id", "fare_product_name", "fare_media_id", "amount", "currency"],
          [[pid, name, "efectivo", f"{amount:.2f}", "COP"] for pid, name, amount in FARE_PRODUCTS])  # ISO 4217: COP has 2 decimals
    rows = []
    for net, a, b, product in FARE_LEGS:
        rows.append([f"{net}-{a}-{b}", net, a, b, product])
        rows.append([f"{net}-{b}-{a}", net, b, a, product])
    write("fare_leg_rules.txt", ["leg_group_id", "network_id", "from_area_id", "to_area_id", "fare_product_id"], rows)


def build(start, end, stops_csv):
    write("agency.txt", list(AGENCY), [list(AGENCY.values())])

    write("stops.txt", ["stop_id", "stop_name", "stop_lat", "stop_lon", "stop_url"], load_stops(stops_csv))

    write("routes.txt", ["route_id", "agency_id", "route_short_name", "route_long_name", "route_desc", "route_type"],
          [[rid, "RMR", "", name, desc, 3] for rid, name, desc, _ in ROUTES])
    write("route_networks.txt", ["network_id", "route_id"], [[net, rid] for rid, _, _, net in ROUTES])

    write_fares()

    # Service calendars: buses run the same every day; vans and microbuses
    # have weekday peaks. Holidays on weekdays run the weekend pattern.
    write("calendar.txt",
          ["service_id", "monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday", "start_date", "end_date"],
          [["DAILY", 1, 1, 1, 1, 1, 1, 1, start, end],
           ["WEEKDAY", 1, 1, 1, 1, 1, 0, 0, start, end],
           ["WEEKEND", 0, 0, 0, 0, 0, 1, 1, start, end]])

    d0 = dt.datetime.strptime(start, "%Y%m%d").date()
    d1 = dt.datetime.strptime(end, "%Y%m%d").date()
    co = holidays.Colombia(years=range(d0.year, d1.year + 1))
    exceptions = []
    for day in sorted(co):
        if d0 <= day <= d1 and day.weekday() < 5:
            ds = day.strftime("%Y%m%d")
            exceptions += [["WEEKDAY", ds, 2], ["WEEKEND", ds, 1]]
    write("calendar_dates.txt", ["service_id", "date", "exception_type"], exceptions)

    with open(ROOT / "shapes.txt", newline="", encoding="utf-8") as f:
        known_shapes = {r["shape_id"] for r in csv.DictReader(f)}

    trips, stop_times, freqs = [], [], []
    for vehicle, rid, direction, headsign, pattern, shape, first, last, peak, base in SERVICES:
        dir_name = "out" if direction == 0 else "in"
        day_types = [("DAILY", False)] if peak == base else [("WEEKDAY", True), ("WEEKEND", False)]
        for service_id, with_peaks in day_types:
            trip_id = f"{rid}-{dir_name}-{vehicle}-{service_id}"
            if shape and shape not in known_shapes:
                print(f"warning: shape {shape} not in shapes.txt, run build_shapes.py")
                shape = ""
            trips.append([rid, service_id, trip_id, headsign, direction, shape])
            t0 = secs(first)
            for seq, (stop_id, minutes) in enumerate(pattern, 1):
                t = hms(t0 + minutes * 60)
                stop_times.append([trip_id, t, t, stop_id, seq])
            for a, b, h in frequency_blocks(first, last, peak, base, with_peaks):
                freqs.append([trip_id, a, b, h, 0])

    write("trips.txt", ["route_id", "service_id", "trip_id", "trip_headsign", "direction_id", "shape_id"], trips)
    write("stop_times.txt", ["trip_id", "arrival_time", "departure_time", "stop_id", "stop_sequence"], stop_times)
    write("frequencies.txt", ["trip_id", "start_time", "end_time", "headway_secs", "exact_times"], freqs)

    write("feed_info.txt",
          ["feed_publisher_name", "feed_publisher_url", "feed_lang", "feed_start_date", "feed_end_date", "feed_version", "feed_contact_url"],
          [["ColombiaTransit", "https://github.com/ColombiaTransit/gtfs-rapido-medellin-rionegro", "es",
            start, end, dt.date.today().strftime("%Y%m%d"),
            "https://github.com/ColombiaTransit/gtfs-rapido-medellin-rionegro/issues"]])


GTFS_FILES = ["agency.txt", "stops.txt", "routes.txt", "trips.txt", "stop_times.txt", "frequencies.txt",
              "calendar.txt", "calendar_dates.txt", "shapes.txt", "feed_info.txt",
              "networks.txt", "route_networks.txt", "areas.txt", "stop_areas.txt", "fare_media.txt", "fare_products.txt", "fare_leg_rules.txt"]


def main():
    today = dt.date.today()
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--stops", default=str(ROOT.parent / "colombia-stops" / "data" / "stops.csv"),
                   help="stops.csv of the colombia-stops registry")
    p.add_argument("--start", default=today.strftime("%Y%m%d"))
    p.add_argument("--end", default=f"{today.year + 1}1231")
    p.add_argument("--zip", action="store_true", help="also write gtfs.zip")
    args = p.parse_args()
    build(args.start, args.end, args.stops)
    if args.zip:
        with zipfile.ZipFile(ROOT / "gtfs.zip", "w", zipfile.ZIP_DEFLATED) as z:
            for name in GTFS_FILES:
                z.write(ROOT / name, name)


if __name__ == "__main__":
    main()
