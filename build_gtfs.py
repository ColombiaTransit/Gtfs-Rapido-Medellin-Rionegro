#!/usr/bin/env python3
"""Generate the GTFS feed for Rápido Medellín Rionegro.

Times and frequencies follow the operator's own route page:
https://www.rapidomedellin.com/rutas/intermunicipales/21

Where the operator gives a range ("every 6-15 minutes, depending on demand"),
the lower value is used in the weekday peaks and the upper value otherwise.
Colombian public holidays (python `holidays` package) run the weekend pattern.

Usage:
    python build_gtfs.py [--start YYYYMMDD] [--end YYYYMMDD] [--zip]

shapes.txt is maintained by hand and is not generated by this script.
"""

import argparse
import csv
import datetime as dt
import zipfile
from pathlib import Path

import holidays

ROOT = Path(__file__).resolve().parent

# Weekday peak periods (no official definition in Colombia; typical commuter peaks).
PEAKS = [("05:00:00", "08:30:00"), ("16:30:00", "19:30:00")]

AGENCY = {
    "agency_id": "RMR",
    "agency_name": "Rápido Medellín Rionegro",
    "agency_url": "https://www.rapidomedellin.com/",
    "agency_timezone": "America/Bogota",
    "agency_lang": "es",
    "agency_phone": "+57 604 480 1640",
}

STOPS = [
    # stop_id, name, lat, lon, url
    ("RMR-RioNegro", "Rionegro - Rápido Medellín Rionegro", 6.1507914, -75.3729361, ""),
    ("RMR-RioNegroAeroPeurto", "Aeropuerto José María Córdova", 6.170909, -75.427822, ""),
    ("TdT-Medellin-Norte", "Medellín - Terminal del Norte", 6.2482327, -75.5958372, "https://www.terminalesmedellin.com/"),
    ("TdT-Medellin-Sur", "Medellín - Terminal del Sur", 6.216341231, -75.58712571, "https://www.terminalesmedellin.com/"),
]

ROUTES = [
    # route_id, long name, desc
    ("RMR-RioNegro-TdT-Medellin-Norte", "Rionegro - Terminal del Norte", "Vía autopista Medellín - Bogotá"),
    ("RMR-RioNegro-TdT-Medellin-Sur", "Rionegro - Terminal del Sur", "Vía Santa Elena - glorieta aeropuerto JMC"),
    ("RMR-RioNegro-TdT-Medellin-Norte-Llanogrande", "Rionegro - Terminal del Norte por Llanogrande",
     "Vía Llanogrande - aeropuerto JMC - autopista"),
]

# Patterns: list of (stop_id, minutes after departure).
NORTE_OUT = [("RMR-RioNegro", 0), ("TdT-Medellin-Norte", 60)]
NORTE_IN = [("TdT-Medellin-Norte", 0), ("RMR-RioNegro", 60)]
SUR_OUT = [("RMR-RioNegro", 0), ("RMR-RioNegroAeroPeurto", 30), ("TdT-Medellin-Sur", 90)]
SUR_IN = [("TdT-Medellin-Sur", 0), ("RMR-RioNegroAeroPeurto", 60), ("RMR-RioNegro", 90)]
LLANO_OUT = [("RMR-RioNegro", 0), ("RMR-RioNegroAeroPeurto", 30), ("TdT-Medellin-Norte", 90)]

SHAPE_NORTE_OUT = "Medellin-TerminalNorte_RMR-RioNegro-TdT-Medellin-Norte"
SHAPE_NORTE_IN = "Rionegro_RMR-RioNegro-TdT-Medellin-Norte"
SHAPE_SUR_OUT = "Medellin-TerminalSur_RMR-RioNegro-TdT-Medellin-Sur"
SHAPE_SUR_IN = "Rionegro_RMR-RioNegro-TdT-Medellin-Sur"

# Services operated, per the operator's page.
# vehicle, route_id, direction, headsign, pattern, shape, first, last, peak headway (min), base headway (min)
SERVICES = [
    ("Van", "RMR-RioNegro-TdT-Medellin-Norte", 0, "Medellín - Terminal del Norte", NORTE_OUT, SHAPE_NORTE_OUT, "04:30:00", "22:00:00", 6, 15),
    ("Van", "RMR-RioNegro-TdT-Medellin-Norte", 1, "Rionegro", NORTE_IN, SHAPE_NORTE_IN, "04:30:00", "22:00:00", 6, 15),
    ("Microbus", "RMR-RioNegro-TdT-Medellin-Norte", 0, "Medellín - Terminal del Norte", NORTE_OUT, SHAPE_NORTE_OUT, "04:30:00", "22:00:00", 7, 15),
    ("Microbus", "RMR-RioNegro-TdT-Medellin-Norte", 1, "Rionegro", NORTE_IN, SHAPE_NORTE_IN, "04:30:00", "22:00:00", 7, 15),
    ("Bus", "RMR-RioNegro-TdT-Medellin-Norte", 0, "Medellín - Terminal del Norte", NORTE_OUT, SHAPE_NORTE_OUT, "05:00:00", "20:00:00", 15, 15),
    ("Bus", "RMR-RioNegro-TdT-Medellin-Norte", 1, "Rionegro", NORTE_IN, SHAPE_NORTE_IN, "05:00:00", "20:00:00", 15, 15),
    ("Bus", "RMR-RioNegro-TdT-Medellin-Sur", 0, "Medellín - Terminal del Sur", SUR_OUT, SHAPE_SUR_OUT, "05:00:00", "20:00:00", 30, 30),
    ("Bus", "RMR-RioNegro-TdT-Medellin-Sur", 1, "Rionegro", SUR_IN, SHAPE_SUR_IN, "05:00:00", "20:00:00", 30, 30),
    ("Bus", "RMR-RioNegro-TdT-Medellin-Norte-Llanogrande", 0, "Medellín - Terminal del Norte", LLANO_OUT, "", "06:00:00", "18:00:00", 60, 60),
]


def secs(t):
    h, m, s = map(int, t.split(":"))
    return h * 3600 + m * 60 + s


def hms(n):
    return f"{n // 3600:02d}:{n % 3600 // 60:02d}:{n % 60:02d}"


def frequency_blocks(first, last, peak_min, base_min, with_peaks):
    """Split [first, last] into periods with peak or base headways.

    end_time is set one second after the last departure so that the last
    departure listed by the operator is included.
    """
    start, end = secs(first), secs(last) + 1
    cuts = []
    if with_peaks and peak_min != base_min:
        for p0, p1 in PEAKS:
            a, b = max(secs(p0), start), min(secs(p1), end)
            if a < b:
                cuts.append((a, b))
    blocks, cur = [], start
    for a, b in cuts:
        if cur < a:
            blocks.append((cur, a, base_min))
        blocks.append((a, b, peak_min))
        cur = b
    if cur < end:
        blocks.append((cur, end, base_min))
    return [(hms(a), hms(b), m * 60) for a, b, m in blocks]


def write(name, header, rows):
    with open(ROOT / name, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


def build(start, end):
    write("agency.txt", list(AGENCY), [list(AGENCY.values())])

    write("stops.txt", ["stop_id", "stop_name", "stop_lat", "stop_lon", "stop_url"],
          [list(s) for s in STOPS])

    write("routes.txt", ["route_id", "agency_id", "route_short_name", "route_long_name", "route_desc", "route_type"],
          [[rid, "RMR", "", name, desc, 3] for rid, name, desc in ROUTES])

    # Service calendars: buses run the same every day; vans and microbuses
    # have weekday peaks. Holidays on weekdays run the weekend pattern.
    write("calendar.txt",
          ["service_id", "monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday", "start_date", "end_date"],
          [["DAILY", 1, 1, 1, 1, 1, 1, 1, start, end],
           ["WEEKDAY", 1, 1, 1, 1, 1, 0, 0, start, end],
           ["WEEKEND", 0, 0, 0, 0, 0, 1, 1, start, end]])

    d0 = dt.datetime.strptime(start, "%Y%m%d").date()
    d1 = dt.datetime.strptime(end, "%Y%m%d").date()
    co = holidays.Colombia(years=range(d0.year, d1.year + 1))
    exceptions = []
    for day in sorted(co):
        if d0 <= day <= d1 and day.weekday() < 5:
            ds = day.strftime("%Y%m%d")
            exceptions += [["WEEKDAY", ds, 2], ["WEEKEND", ds, 1]]
    write("calendar_dates.txt", ["service_id", "date", "exception_type"], exceptions)

    trips, stop_times, freqs = [], [], []
    for vehicle, rid, direction, headsign, pattern, shape, first, last, peak, base in SERVICES:
        dir_name = "out" if direction == 0 else "in"
        day_types = [("DAILY", False)] if peak == base else [("WEEKDAY", True), ("WEEKEND", False)]
        for service_id, with_peaks in day_types:
            trip_id = f"{rid}-{dir_name}-{vehicle}-{service_id}"
            trips.append([rid, service_id, trip_id, headsign, direction, shape])
            t0 = secs(first)
            for seq, (stop_id, minutes) in enumerate(pattern, 1):
                t = hms(t0 + minutes * 60)
                stop_times.append([trip_id, t, t, stop_id, seq])
            for a, b, h in frequency_blocks(first, last, peak, base, with_peaks):
                freqs.append([trip_id, a, b, h, 0])

    write("trips.txt", ["route_id", "service_id", "trip_id", "trip_headsign", "direction_id", "shape_id"], trips)
    write("stop_times.txt", ["trip_id", "arrival_time", "departure_time", "stop_id", "stop_sequence"], stop_times)
    write("frequencies.txt", ["trip_id", "start_time", "end_time", "headway_secs", "exact_times"], freqs)

    write("feed_info.txt",
          ["feed_publisher_name", "feed_publisher_url", "feed_lang", "feed_start_date", "feed_end_date", "feed_version", "feed_contact_url"],
          [["ColombiaTransit", "https://github.com/ColombiaTransit/gtfs-rapido-medellin-rionegro", "es",
            start, end, dt.date.today().strftime("%Y%m%d"),
            "https://github.com/ColombiaTransit/gtfs-rapido-medellin-rionegro/issues"]])


GTFS_FILES = ["agency.txt", "stops.txt", "routes.txt", "trips.txt", "stop_times.txt", "frequencies.txt",
              "calendar.txt", "calendar_dates.txt", "shapes.txt", "feed_info.txt"]


def main():
    today = dt.date.today()
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--start", default=today.strftime("%Y%m%d"))
    p.add_argument("--end", default=f"{today.year + 1}1231")
    p.add_argument("--zip", action="store_true", help="also write gtfs.zip")
    args = p.parse_args()
    build(args.start, args.end)
    if args.zip:
        with zipfile.ZipFile(ROOT / "gtfs.zip", "w", zipfile.ZIP_DEFLATED) as z:
            for name in GTFS_FILES:
                z.write(ROOT / name, name)


if __name__ == "__main__":
    main()
